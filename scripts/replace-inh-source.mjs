#!/usr/bin/env node
/**
 * replace-inh-source.mjs
 *
 * Replaces the `inh` field of every entry in
 *   src/content/quran-sources.ts
 * with the literary Ingush translation from
 *   data/inh-quran/quran_translation_ing_smisl.db
 *   ("ГӀалгӀай — Сийдолча КъорӀан маӀана таржам", 2023).
 *
 * The previous inh content (a mix of word-by-word and patchwork sources
 * the user collected manually for surahs 67/78–112) is dropped completely.
 * Arabic and Russian-Kuliev fields are kept untouched — only `inh` changes.
 *
 * The script is idempotent: running it twice produces the same output.
 *
 * Run:  node scripts/replace-inh-source.mjs
 * Deps: better-sqlite3 (`npm install -D better-sqlite3 --prefix scripts/.deps`)
 *       OR fall back to a system `sqlite3` binary if that's not available.
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT       = resolve(__dirname, '..');
const SOURCES_TS = resolve(ROOT, 'src/content/quran-sources.ts');
const DB_PATH    = resolve(ROOT, 'data/inh-quran/quran_translation_ing_smisl.db');

if (!existsSync(SOURCES_TS)) throw new Error(`missing ${SOURCES_TS}`);
if (!existsSync(DB_PATH))    throw new Error(`missing ${DB_PATH}`);

// ── Load all (sura, aya) → translation from SQLite ──────────────────────────
// Use the system `sqlite3` CLI to avoid pulling a native dep into the repo.
// The DB is small (1.4 MB, 6236 rows) so a single SELECT-everything is fine.

function loadInhMap() {
  const stdout = execFileSync(
    'sqlite3',
    ['-separator', '\x1e', '-newline', '\x1f', DB_PATH,
     'SELECT sura, aya, translation FROM translations ORDER BY sura, aya'],
    { encoding: 'utf-8', maxBuffer: 32 * 1024 * 1024 },
  );

  const map = new Map();
  // Each row is "sura\x1eaya\x1etranslation\x1f"
  const rows = stdout.split('\x1f').filter(r => r.trim());
  for (const row of rows) {
    const parts = row.split('\x1e');
    if (parts.length < 3) continue;
    const sura = parseInt(parts[0], 10);
    const aya  = parseInt(parts[1], 10);
    const text = parts.slice(2).join('\x1e').trim();   // joins-back if text had \x1e (it shouldn't)
    if (!sura || !aya || !text) continue;
    map.set(`${sura}:${aya}`, text);
  }
  return map;
}

// ── Escape for a single-quote TS string literal ─────────────────────────────

function escStr(s) {
  return s
    .replace(/\\/g, '\\\\')
    .replace(/'/g, "\\'");
}

// ── Replace inh in every entry ──────────────────────────────────────────────
//
// Entry shape (one per line in the file):
//   '67:1': { surah: 67, ayah: 1, arabic: '...', translations: { ru: '...', inh: '...' }, editions: { ... }, fetchedAt: '...' },
//
// The inh segment can be present (with content) or absent.  We rewrite
// `translations: { ru: '...' }` and `translations: { ru: '...', inh: '...' }`
// uniformly to `translations: { ru: '...', inh: '<NEW>' }`.
//
// Strategy: find each entry's `translations: { ... }` block (single-line),
// extract the `ru: '...'` inside, then rebuild the block with the new inh.
//
// We do NOT regex over single-quote contents — instead we walk character by
// character per line, respecting backslash escapes.  A single-quote rule is
// enough because the file is generated by escStr().

function rebuildLine(line, inhMap) {
  // Match `'<sura>:<aya>':` at line start (after optional whitespace).
  const keyMatch = line.match(/^(\s*)'(\d+):(\d+)':\s*\{/);
  if (!keyMatch) return line;
  const key = `${keyMatch[2]}:${keyMatch[3]}`;
  const newInh = inhMap.get(key);
  // Find `translations: {` ... `}` substring.
  const transStart = line.indexOf('translations: {');
  if (transStart === -1) return line;
  // Walk forward to find the matching closing brace, respecting strings.
  let i = transStart + 'translations: {'.length;
  let depth = 1;
  let inStr = false;
  while (i < line.length && depth > 0) {
    const ch = line[i];
    if (inStr) {
      if (ch === '\\' && i + 1 < line.length) { i += 2; continue; }
      if (ch === "'") inStr = false;
    } else {
      if (ch === "'") inStr = true;
      else if (ch === '{') depth++;
      else if (ch === '}') depth--;
    }
    i++;
  }
  if (depth !== 0) {
    process.stderr.write(`! could not parse line for ${key}\n`);
    return line;
  }
  const transEnd = i;                    // exclusive index just past closing }
  const inner    = line.slice(transStart + 'translations: {'.length, transEnd - 1);

  // Extract ru: '...' value from inner.  Walk forward to find ru: '<text>'.
  const ruIdx = inner.indexOf("ru:");
  if (ruIdx === -1) {
    process.stderr.write(`! ${key}: no ru in translations\n`);
    return line;
  }
  let j = ruIdx + 'ru:'.length;
  while (j < inner.length && inner[j] !== "'") j++;
  if (inner[j] !== "'") return line;
  j++;                                   // past opening quote
  let ruVal = '';
  while (j < inner.length) {
    const ch = inner[j];
    if (ch === '\\' && j + 1 < inner.length) {
      ruVal += ch + inner[j + 1];
      j += 2;
      continue;
    }
    if (ch === "'") break;
    ruVal += ch;
    j++;
  }

  // Build replacement block.
  let newTrans;
  if (newInh) {
    newTrans = `translations: { ru: '${ruVal}', inh: '${escStr(newInh)}' }`;
  } else {
    // No literary Ingush available for this verse — keep ru only.
    newTrans = `translations: { ru: '${ruVal}' }`;
  }

  return line.slice(0, transStart) + newTrans + line.slice(transEnd);
}

// ── Main ────────────────────────────────────────────────────────────────────

function main() {
  console.log('Loading Ingush smisl translations from SQLite...');
  const inhMap = loadInhMap();
  console.log(`  ${inhMap.size} verses loaded`);

  console.log(`Reading ${SOURCES_TS}...`);
  const src = readFileSync(SOURCES_TS, 'utf-8');
  const lines = src.split('\n');
  console.log(`  ${lines.length} lines`);

  let touched = 0;
  let withInh = 0;
  let withoutInh = 0;
  for (let i = 0; i < lines.length; i++) {
    const before = lines[i];
    const after  = rebuildLine(before, inhMap);
    if (before !== after) {
      touched++;
      const keyMatch = after.match(/^\s*'(\d+):(\d+)':/);
      if (keyMatch) {
        const has = after.includes(", inh: '");
        if (has) withInh++; else withoutInh++;
      }
    }
    lines[i] = after;
  }

  // Replace the comment block at the top describing Ingush sourcing.
  const newHeader = `// Источники кораничного текста
// Арабский: alquran.cloud quran-uthmani / MCP fetch_quran (см. отдельные блоки ниже)
// Русский:  alquran.cloud ru.kuliev (Эльмир Кулиев)
// Ингушский: ГӀалгӀай — Сийдолча КъорӀан маӀана таржам (2023),
//            автор/издатель: ing.galgaev (Android-приложение
//            «Коран и Сунна»). Источник:
//            data/inh-quran/quran_translation_ing_smisl.db (см. README в этой
//            папке). Заполнен скриптом scripts/replace-inh-source.mjs.`;

  // Replace original header (first comment block before "export type").
  const exportIdx = lines.findIndex(l => l.startsWith('export type QuranSource'));
  if (exportIdx > 0) {
    lines.splice(0, exportIdx, newHeader, '');
  }

  writeFileSync(SOURCES_TS, lines.join('\n'), 'utf-8');
  console.log(`Wrote ${SOURCES_TS}`);
  console.log(`  touched lines: ${touched}`);
  console.log(`  with new inh:    ${withInh}`);
  console.log(`  without inh:     ${withoutInh} (verses missing in smisl.db)`);
}

main();
