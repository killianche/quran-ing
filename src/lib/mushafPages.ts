/**
 * Таблица страниц нужного издания.
 *
 * Умолчание — издание 1441: на него опираются лента и цветной таджвид,
 * у которых своей разбивки нет.  Кому нужны страницы «Мадани 1405», тот
 * обязан передать издание явно, иначе промахнётся мимо аята.
 */
function tableFor(edition: QcfEdition): number[] {
  return edition === 'qcf-v1' ? FIRST_AYAH_OF_PAGE_V1 : FIRST_AYAH_OF_PAGE;
}

/** Номер страницы, на которой начинается аят.  Вне диапазона — 1. */
export function pageOfAyah(
  surah: number,
  ayah: number,
  edition: QcfEdition = DEFAULT_QCF_EDITION,
): number {
  const g = globalAyahNumber(surah, ayah);
  if (!Number.isFinite(g) || g < 1) return 1;
  const table = tableFor(edition);
  // Ищем последнюю страницу, чей первый аят не позже искомого.
  let lo = 0, hi = table.length - 1, ans = 0;
  while (lo <= hi) {
    const mid = (lo + hi) >> 1;
    if (table[mid] <= g) { ans = mid; lo = mid + 1; }
    else hi = mid - 1;
  }
  return ans + 1;
}

/** Сквозной номер первого аята страницы — для проверок. */
export function firstAyahOfPage(
  page: number,
  edition: QcfEdition = DEFAULT_QCF_EDITION,
): number {
  const p = Math.min(MUSHAF_PAGES, Math.max(1, Math.round(page)));
  return tableFor(edition)[p - 1];
}

/**
 * С какого места читать, если человек уходит со страницы мусхафа в ленту.
 *
 * Нужно переключателю «книга ↔ лента»: он должен вернуть человека туда,
 * где тот стоял, а не в начало суры.  Считается из той же таблицы, что и
 * `pageOfAyah`, поэтому переход в обе стороны сходится на одном аяте.
 */
export function surahAyahOfPage(
  page: number,
  edition: QcfEdition = DEFAULT_QCF_EDITION,
): { surah: number; ayah: number } {
  const global = firstAyahOfPage(page, edition);
  // Идём от последней суры к первой: первая, чьё начало не позже нашего
  // аята, и есть нужная.
  for (let surah = TOTAL_SURAHS; surah >= 1; surah--) {
    const start = firstGlobalOfSurah(surah);
    if (start <= global) {
      return { surah, ayah: global - start + 1 };
    }
  }
  return { surah: 1, ayah: 1 };
}
