/**
 * fastScroll — быстрая прокрутка удержанием у левого края.
 *
 * Владелец 10.09.2026: «по левому краю кликаешь — открывается быстрая
 * прокрутка по аятам… На главной — кликаю на цифру суры и прокручиваю
 * быстренько вниз-вверх». Образец — сторонняя читалка: полоса у края и
 * крупный номер аята по центру экрана.
 *
 * ── Почему удержание, а не касание ─────────────────────────────────────
 *
 * Левый край — это и место, откуда люди просто листают список большим
 * пальцем. Полоса, хватающая любое касание, сломала бы обычную прокрутку
 * у края, а на главной — ещё и тап по номеру суры. Удержание около 0.2 с
 * отделяет намерение: так же в iOS «хватают» индикатор прокрутки. Быстрое
 * движение и тап проходят сквозь, как раньше.
 *
 * ── Почему выключатель на каждое место ────────────────────────────────
 *
 * Владелец попросил, чтобы функцию можно было быстро убрать в одном месте,
 * а в другом оставить. Один флаг — одно место; `false` выключает полосу
 * целиком, вместе с обработчиками касаний.
 */

export const FAST_SCROLL = {
  /** Главная: удержание на номере суры и протяжка вверх-вниз по сурам. */
  surahList: true,
  /** Лента суры: удержание у левого края, по аятам. */
  ayahFeed: true,
} as const;

/** Сколько держать палец неподвижно, прежде чем включится прокрутка, мс. */
export const HOLD_MS = 220;

/**
 * Сдвиг до включения, после которого это уже не удержание, а обычная
 * прокрутка или тап, px.
 */
export const HOLD_SLOP = 8;

const clamp = (v: number, lo: number, hi: number) => Math.min(hi, Math.max(lo, v));

/**
 * Номер позиции (с единицы) под пальцем во время быстрой прокрутки.
 *
 * 🔴 Считаем от ТОЧКИ УДЕРЖАНИЯ, а не по всей высоте экрана. Иначе нажатие
 * на суру 36 посреди списка мгновенно прыгало бы к 57-й — к середине
 * диапазона: палец стоит на месте, а список уехал. Здесь в момент включения
 * под пальцем ровно та позиция, на которой держали.
 *
 * При этом до краёв достать можно всегда: вниз от точки удержания путь до
 * низа дорожки делится на оставшиеся позиции, вверх — на пройденные. Низ
 * дорожки — последняя позиция, верх — первая, откуда бы ни начали.
 */
export function scrubIndex({ y, y0, top, bottom, n0, count }: {
  /** Где палец сейчас, px от верха экрана. */
  y: number;
  /** Где удерживали в момент включения. */
  y0: number;
  /** Границы дорожки по вертикали. */
  top: number;
  bottom: number;
  /** Позиция под пальцем в момент включения. */
  n0: number;
  /** Сколько всего позиций. */
  count: number;
}): number {
  if (count <= 1) return 1;
  const start = clamp(Math.round(n0), 1, count);
  const lo = Math.min(top, bottom);
  const hi = Math.max(top, bottom);
  const anchor = clamp(y0, lo, hi);
  const at = clamp(y, lo, hi);
  const n = at >= anchor
    ? start + ((at - anchor) / Math.max(1, hi - anchor)) * (count - start)
    : start - ((anchor - at) / Math.max(1, anchor - lo)) * (start - 1);
  return clamp(Math.round(n), 1, count);
}
